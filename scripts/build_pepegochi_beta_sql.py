"""Build games/supabase/deploy/PEPEGOCHI_BETA.sql: PepeGochi + Pond Quiz for the hidden beta, ONE transaction.

The game, the room, Room-4 (moving out with one item) and the Pond Quiz, without anything that awards a Passport
stamp: update_pepegochi_passport.sql (First Hatch, Little Fren, One Small Step, Good Parent) and
update_pepegochi_rewards.sql (decorations, Pond Decorator) wait for the launch, and passport_award() is not changed,
so the quiz stamps wait too. Nothing is lost: on launch day those files deliver every milestone reached in the
beta, dated when it happened. The questions come separately, from the owner's PRIVATE file.
Each file's own top-level `begin;` / `commit;` lines and its '--' comments are taken out.
Run: python3 scripts/build_pepegochi_beta_sql.py   (--check: exit 1 when the output is out of date)
"""
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
SUPA = os.path.join(ROOT, 'games', 'supabase')
OUT = os.path.join(SUPA, 'deploy', 'PEPEGOCHI_BETA.sql')
TX = re.compile(r'^\s*(begin|commit)\s*;\s*$', re.I)
COMMENT = re.compile(r'\s*--.*$')
FILES = ['update_pepegochi_v2.sql', 'update_pepegochi_room_v1.sql', 'update_pepegochi_room_departure.sql',
         'update_pond_quiz.sql']


def read(name):
    with open(os.path.join(SUPA, name), encoding='utf-8') as f:
        lines = [COMMENT.sub('', line).rstrip() for line in f.read().splitlines() if not TX.match(line)]
    return '\n'.join(line for line in lines if line).rstrip()


def build():
    n = len(FILES)
    parts = ['/* PepeGochi + Pond Quiz, hidden beta (only with ?beta=gochi). No Passport stamp is awarded yet.',
             '   GENERATED by scripts/build_pepegochi_beta_sql.py from games/supabase/ (comments taken out). Do not edit here.',
             '   Supabase > SQL Editor > New query > paste ALL of this > Run. One transaction: any error and nothing is applied.',
             '   Then run the PRIVATE update_pond_quiz_questions.sql (the 99 questions). Both are safe to run again. */',
             '', 'begin;', '']
    for i, name in enumerate(FILES, 1):
        parts += ['/* %d/%d  %s */' % (i, n, name), read(name), '']
    parts += ['commit;', '',
              '/* Check (optional, run on its own afterwards, after the questions file): every column should say true.',
              "select to_regprocedure('public.gry_pepegochi_state()') is not null as pepegochi,",
              "       to_regprocedure('public.gry_pepegochi_room_state()') is not null as room,",
              "       to_regprocedure('public.gry_pepegochi_settle()') is not null as moving_out,",
              "       to_regprocedure('public.gry_quiz_today()') is not null as quiz,",
              "       (select count(*) from games.quiz_questions where active) = 99 as questions;",
              '*/', '']
    return '\n'.join(parts)


if __name__ == '__main__':
    text = build()
    if '--check' in sys.argv:
        with open(OUT, encoding='utf-8') as f:
            sys.exit(0 if f.read() == text else 1)
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(text)
    print('wrote', os.path.relpath(OUT, ROOT), len(text), 'bytes')
