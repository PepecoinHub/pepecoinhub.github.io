"""Build games/supabase/deploy/POND_DUELS_ALL.sql: the POND duels in ONE transaction, ready to paste.

POND BULLETIN, POND KING, BATTLE OF THREE LILIES (with their records), then the Fren Passport award path
(games.passport_award from update_passport_awards.sql) again, so it knows the 'long_live_the_king' stamp.
Only that one function is taken from update_passport_awards.sql: the rest of that file is already live.
Each file's own top-level `begin;` / `commit;` lines are taken out.
Run: python3 scripts/build_pond_sql.py   (--check: exit 1 when the output is out of date)
"""
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
SUPA = os.path.join(ROOT, 'games', 'supabase')
OUT = os.path.join(SUPA, 'deploy', 'POND_DUELS_ALL.sql')
TX = re.compile(r'^\s*(begin|commit)\s*;\s*$', re.I)
FILES = ['update_pond_bulletin.sql', 'update_pond_king.sql', 'update_lilies.sql']


def read(name):
    with open(os.path.join(SUPA, name), encoding='utf-8') as f:
        return '\n'.join(line for line in f.read().splitlines() if not TX.match(line)).rstrip()


def award():
    text = read('update_passport_awards.sql')
    m = re.search(r'create or replace function games\.passport_award\(.*?\n\$\$;', text, re.S)
    if not m or 'long_live_the_king' not in m.group(0):
        raise SystemExit('games.passport_award with long_live_the_king not found')
    return m.group(0)


def build():
    parts = ['-- POND duels: Pond Bulletin, Pond King, Battle of Three Lilies (+ records) and the Long Live the King stamp.',
             '-- GENERATED by scripts/build_pond_sql.py from games/supabase/. Do not edit here: edit the files and run the script.',
             '-- Supabase > SQL Editor > New query > paste ALL of this > Run. One transaction: any error and nothing is applied.',
             '-- Needs schema.sql and the Fren Passport launch (deploy/LAUNCH_ALL.sql), both already live. Safe to run again.',
             '', 'begin;', '']
    for i, name in enumerate(FILES, 1):
        parts += ['-- ' + '=' * 100, '-- %d/4  %s' % (i, name), '-- ' + '=' * 100, read(name), '']
    parts += ['-- ' + '=' * 100, '-- 4/4  update_passport_awards.sql: games.passport_award only (adds long_live_the_king)',
              '-- ' + '=' * 100, award(), '', 'commit;', '',
              '-- Check (optional, read only): every row should say true.',
              "-- select to_regprocedure('public.gry_bulletin(int)') is not null as bulletin,",
              "--        to_regprocedure('public.gry_pk_state(text)') is not null as pond_king,",
              "--        to_regprocedure('public.gry_lily_leaders()') is not null as lilies,",
              "--        pg_get_functiondef('games.passport_award(uuid,text,timestamptz)'::regprocedure) like '%long_live_the_king%' as stamp;",
              '']
    return '\n'.join(parts)


if __name__ == '__main__':
    text = build()
    if '--check' in sys.argv:
        with open(OUT, encoding='utf-8') as f:
            sys.exit(0 if f.read() == text else 1)
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(text)
    print('wrote', os.path.relpath(OUT, ROOT), len(text), 'bytes')
