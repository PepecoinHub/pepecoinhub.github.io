"""Build games/supabase/deploy/EXPANSION7.sql: the Fren Passport expansion 7 server part in ONE transaction, ready to paste.

1. games.passport_award from update_passport_awards.sql (only that function: the rest of the file is live); its
   allowlist now also knows 'super_parent' (PepeGochi delivers it, on PepeGochi day).
2. update_passport_arcade_x7.sql: the Three Lilies and Gold Hook counters for Lord of the Lilies, Master Tactician,
   Gold Digger and Gold Rush. These four stay out of the allowlist: progress is recorded, nothing is awarded yet.
Each file's own top-level `begin;` / `commit;` lines and its '--' comments are taken out.
Run: python3 scripts/build_expansion7_sql.py   (--check: exit 1 when the output is out of date)
"""
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
SUPA = os.path.join(ROOT, 'games', 'supabase')
OUT = os.path.join(SUPA, 'deploy', 'EXPANSION7.sql')
OUT_ON = os.path.join(SUPA, 'deploy', 'EXPANSION7_LILIES_ON.sql')
TX = re.compile(r'^\s*(begin|commit)\s*;\s*$', re.I)
COMMENT = re.compile(r'\s*--.*$')


def clean(text):
    lines = [COMMENT.sub('', line).rstrip() for line in text.splitlines() if not TX.match(line)]
    return '\n'.join(line for line in lines if line).rstrip()


def read(name):
    with open(os.path.join(SUPA, name), encoding='utf-8') as f:
        return f.read()


def award():
    m = re.search(r'create or replace function games\.passport_award\(.*?\n\$\$;', read('update_passport_awards.sql'), re.S)
    if not m or "'super_parent'" not in m.group(0):
        raise SystemExit('games.passport_award with super_parent not found')
    return clean(m.group(0))


def build():
    x7 = read('update_passport_arcade_x7.sql')
    undo = x7.split('-- Undo (if ever needed):')[0]   # the undo notes stay in the source file only
    parts = ['/* Fren Passport expansion 7: Lord of the Lilies, Master Tactician, Gold Digger, Gold Rush (counters only) and',
             '   the Super Parent id in the award allowlist.',
             '   GENERATED by scripts/build_expansion7_sql.py from games/supabase/ (comments taken out). Do not edit here.',
             '   Supabase > SQL Editor > New query > paste ALL of this > Run. One transaction: any error and nothing is applied.',
             '   Needs the Fren Passport launch and the POND duels (Three Lilies), both already live. Safe to run again.',
             '   Gold Hook: if update_gold_hook_campaign.sql is live, paste it again AFTER this (it is safe to run again):',
             '   its new version hands the completed levels to the counters. PepeGochi: Super Parent comes with its own files. */',
             '', 'begin;', '',
             '/* 1/2  update_passport_awards.sql: games.passport_award only (adds super_parent) */', award(), '',
             '/* 2/2  update_passport_arcade_x7.sql */', clean(undo), '', 'commit;', '',
             '/* Check (optional, run on its own afterwards): every column should say true.',
             "select to_regclass('games.passport_x7_progress') is not null as counters,",
             "       exists (select 1 from pg_trigger where tgname = 'passport_lily_after') as lilies_trigger,",
             "       pg_get_functiondef('games.passport_goldhook_run(uuid,integer)'::regprocedure) like '%passport_x7_progress%' as goldhook_hook,",
             "       pg_get_functiondef('games.passport_award(uuid,text,timestamptz)'::regprocedure) like '%super_parent%' as super_parent;",
             '*/', '']
    return '\n'.join(parts)


def build_on():
    a = award()
    if "'lord_of_the_lilies'" not in a or "'master_tactician'" not in a:
        raise SystemExit('the allowlist does not know the two Three Lilies stamps yet')
    return '\n'.join([
        '/* Fren Passport expansion 7: Lord of the Lilies and Master Tactician ON (owner, 2026-11-17).',
        '   GENERATED by scripts/build_expansion7_sql.py. Do not edit here. Run AFTER EXPANSION7.sql.',
        '   Supabase > SQL Editor > New query > paste ALL of this > Run. One transaction. Safe to run again.',
        '   It puts both stamps into the award allowlist, then gives them at once to everyone whose recorded',
        '   Three Lilies progress already reached 10 wins / a best streak of 5. Gold Digger and Gold Rush stay off. */',
        '', 'begin;', '', a, '',
        'select games.passport_x7_sync(user_id) from games.passport_x7_progress;', '', 'commit;', '',
        '/* Check (optional, run on its own afterwards): who has the two stamps.',
        "select b.badge_id, games.discord_identity(b.user_id)->>'name' as fren, b.earned_at from games.passport_badges b",
        " where b.badge_id in ('lord_of_the_lilies', 'master_tactician') order by b.earned_at;",
        '*/', ''])


if __name__ == '__main__':
    outs = [(OUT, build()), (OUT_ON, build_on())]
    if '--check' in sys.argv:
        for path, text in outs:
            with open(path, encoding='utf-8') as f:
                if f.read() != text:
                    sys.exit(1)
        sys.exit(0)
    for path, text in outs:
        with open(path, 'w', encoding='utf-8') as f:
            f.write(text)
        print('wrote', os.path.relpath(path, ROOT), len(text), 'bytes')
