#!/usr/bin/env python3
"""Build games/supabase/functions/push-send/index.ts: ONE file to paste in Supabase > Edge Functions > Via editor.
It is webpush.mjs (the encryption, tested by tests/push-webpush.test.mjs) + server.ts (the handler).
Usage: python3 scripts/build_push_function.py          (write)
       python3 scripts/build_push_function.py --check  (exit 1 if index.ts is out of date)"""
import os, re, sys
D = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'games', 'supabase', 'functions', 'push-send')
def build():
    wp = open(os.path.join(D, 'webpush.mjs'), encoding='utf-8').read()
    wp = re.sub(r'^export (async function|function|const)', r'\1', wp, flags=re.M)
    srv = open(os.path.join(D, 'server.ts'), encoding='utf-8').read()
    return ('// GENERATED by scripts/build_push_function.py from webpush.mjs + server.ts. Do not edit here.\n'
            '// Supabase > Edge Functions > push-send > Via editor: paste ALL of this file, then Deploy.\n'
            '// @ts-nocheck\n\n' + srv.rstrip() + '\n\n// ---------------------------------------------------------------- webpush.mjs\n' + wp)
out = build(); path = os.path.join(D, 'index.ts')
if '--check' in sys.argv:
    cur = open(path, encoding='utf-8').read() if os.path.exists(path) else ''
    sys.exit(0 if cur == out else 1)
open(path, 'w', encoding='utf-8').write(out)
print('wrote', path)
