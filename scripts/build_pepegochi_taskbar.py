def render(rows):
    if len(rows) != 48:
        raise SystemExit(f"grid has {len(rows)} rows, expected 48")
    img = Image.new("RGBA", (48, 48), (0, 0, 0, 0))
    px = img.load()
    for y, row in enumerate(rows):
        if len(row) != 48:
            raise SystemExit(f"row {y} has {len(row)} columns, expected 48")
        for x, ch in enumerate(row):
            if ch not in PALETTE:
                raise SystemExit(f"unknown pixel {ch!r} at {x},{y}")
            px[x, y] = PALETTE[ch]
    return img


def preview(images):
    gap = 2
    width = len(images) * 48 + (len(images) - 1) * gap
    height = 1 + 48
    bar = Image.new("RGBA", (width, height), (0xC0, 0xC0, 0xC0, 255))
    for x in range(width):
        bar.putpixel((x, 0), (255, 255, 255, 255))
    for i, img in enumerate(images):
        bar.alpha_composite(img, (i * (48 + gap), 1))
    big = bar.resize((width * 4, height * 4), Image.NEAREST)
    space = 6
    sheet = Image.new("RGBA", (big.width, bar.height + space + big.height), (0xC0, 0xC0, 0xC0, 255))
    sheet.paste(bar, ((big.width - bar.width) // 2, 0))
    sheet.paste(big, (0, bar.height + space))
    return sheet


def main():
    root = Path(__file__).resolve().parents[1]
    out = root / "docs" / "games" / "img" / "pepegochi" / "taskbar"
    out.mkdir(parents=True, exist_ok=True)
    images = []
    for name in ORDER:
        img = render(SPRITES[name])
        img.save(out / f"{name}.png")
        images.append(img)
    preview_path = root / "games" / "pepegochi" / "a2-review" / "cursor_bar_preview.png"
    preview(images).save(preview_path)
    print(f"wrote {len(images)} sprites to {out}")
    print(f"wrote {preview_path}")


if __name__ == "__main__":
    main()
