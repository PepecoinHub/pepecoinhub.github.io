def nearest_grid(path):
    """Map a candidate PNG onto the palette. Starting point only.

    The downscales are blurry, so the returned grid is muddy. Clean the
    outline, eyes, mouth, and the white P by hand before saving it in SPRITES.
    """
    img = Image.open(path).convert("RGBA")
    if img.size != (48, 48):
        img = img.resize((48, 48), Image.NEAREST)
    colours = [(ch, rgb) for ch, rgb in PALETTE.items() if ch != "."]
    rows = []
    for y in range(48):
        chars = []
        for x in range(48):
            r, g, b, a = img.getpixel((x, y))
            if a < 128:
                chars.append(".")
                continue
            best, dist = ".", 10**9
            for ch, (cr, cg, cb, _ca) in colours:
                d = (r - cr) ** 2 + (g - cg) ** 2 + (b - cb) ** 2
                if d < dist:
                    best, dist = ch, d
            chars.append(best)
        rows.append("".join(chars))
    return rows


