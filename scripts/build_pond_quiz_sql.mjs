#!/usr/bin/env node
// Writes games/supabase/update_pond_quiz_questions.sql from docs/data/pepecoin-quiz.json, so the server's question
// bank (with the right answers) is always the same as the file the site uses. Run after editing the JSON:
//   node scripts/build_pond_quiz_sql.mjs
// tests/pepecoin-quiz.test.mjs fails when the SQL is out of date.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
export const OUT = 'games/supabase/update_pond_quiz_questions.sql';

const lit = s => (s == null ? 'null' : "'" + String(s).replace(/'/g, "''") + "'");
// a question is asked only with a source on the site and no answer tied to a date (same rule as pepegochi-facts.mjs)
export const isActive = q => !!q.source && !q.dated;

export function buildSql(questions) {
  const rows = questions.map(q => `  (${lit(q.id)}, ${lit(q.question)}, array[${q.answers.map(lit).join(', ')}], ${q.correct}, ` +
    `${lit(q.source)}, ${isActive(q)})`);
  return `-- Pond Quiz question bank. GENERATED by scripts/build_pond_quiz_sql.mjs from docs/data/pepecoin-quiz.json:
-- do not edit by hand. Run after update_pond_quiz.sql. Safe to run again: it updates the questions in place and
-- switches off questions that left the file (answers already given stay).
begin;
insert into games.quiz_questions (id, question, answers, correct, source, active) values
${rows.join(',\n')}
on conflict (id) do update set question = excluded.question, answers = excluded.answers, correct = excluded.correct,
  source = excluded.source, active = excluded.active;
update games.quiz_questions set active = false
  where id not in (${questions.map(q => lit(q.id)).join(', ')});
commit;
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const data = JSON.parse(readFileSync(new URL('docs/data/pepecoin-quiz.json', root), 'utf8'));
  writeFileSync(new URL(OUT, root), buildSql(data.questions));
  console.log('wrote', OUT, data.questions.length, 'questions,', data.questions.filter(isActive).length, 'active');
}
