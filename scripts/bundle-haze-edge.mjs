// Builds one paste-ready file of the haze-wallet Edge Function for the Supabase dashboard editor
// (Edge Functions -> Deploy a new function -> Via editor), so it can be deployed from a phone without the CLI.
// Same code as games/supabase/functions/haze-wallet: local imports are inlined in dependency order and the
// deno.json import map becomes pinned npm: specifiers. `node scripts/bundle-haze-edge.mjs --check` fails when stale.
import fs from 'node:fs';
const dir=new URL('../games/supabase/functions/haze-wallet/',import.meta.url);
const out=new URL('../games/supabase/haze-beta/haze-wallet-dashboard.ts',import.meta.url);
const map=JSON.parse(fs.readFileSync(new URL('deno.json',dir),'utf8')).imports;
const parts=['protocol.mjs','core.mjs','handler.mjs','index.ts'].map(name=>{
  const text=fs.readFileSync(new URL(name,dir),'utf8').replace(/^import [^\n]*from '\.\/[^']+';\n/gm,'')
    .replace(/^(import [^\n]*from ')([^'.][^']*)(';)$/gm,(line,a,spec,b)=>{if(!map[spec])throw Error('No pinned import for '+spec);return a+map[spec]+b;});
  return '// ---- '+name+' ----\n'+text.trim()+'\n';
});
const imports=[],body=[];
for(const part of parts)for(const line of part.split('\n'))(/^import /.test(line)?imports:body).push(line);
const bundle=['// @ts-nocheck','// GENERATED by scripts/bundle-haze-edge.mjs from games/supabase/functions/haze-wallet. Do not edit by hand.',
  '// Supabase dashboard: function name haze-wallet, JWT verification OFF (the function checks the session itself).',...imports,'',...body].join('\n');
// One paste for the Supabase SQL editor: both migrations in their required order (each is its own transaction).
const sqlOut=new URL('../games/supabase/haze-beta/0_install.sql',import.meta.url);
const sql=['-- GENERATED by scripts/bundle-haze-edge.mjs: update_haze_tips.sql + update_haze_groups.sql, in that order.',
  '-- Paste all of it into the Supabase SQL editor and Run. Repeatable. Everything stays OFF (enabled=false, beta_only=true).','',
  ...['update_haze_tips.sql','update_haze_groups.sql'].map(name=>'-- ==== '+name+' ====\n'+fs.readFileSync(new URL('../games/supabase/'+name,import.meta.url),'utf8').trim()+'\n')].join('\n');
// Phone copy/paste truncates long text, so the same SQL and Edge file are also split into small parts.
// SQL: split only between top-level statements (never inside $$ bodies, quotes or comments); each part is its
// own transaction and the parts must run in order. Edge: split between lines; paste each part at the END.
const PART=6000;
function statements(text){
  const out=[];let cur='',i=0,dollar=false,quote=false;
  while(i<text.length){
    const c=text[i],two=text.slice(i,i+2);
    if(!dollar&&!quote&&two==='--'){const end=text.indexOf('\n',i);const stop=end<0?text.length:end+1;cur+=text.slice(i,stop);i=stop;continue;}
    if(!quote&&two==='$$'){dollar=!dollar;cur+=two;i+=2;continue;}
    if(!dollar&&c==="'"){quote=!quote;}
    cur+=c;i++;
    if(!dollar&&!quote&&c===';'){out.push(cur);cur='';}
  }
  if(cur.trim())out.push(cur);
  if(dollar||quote)throw Error('Unbalanced SQL quoting');
  return out.map(x=>x.trim()).filter(x=>x&&!/^(begin|commit);$/i.test(x.replace(/^(--[^\n]*\n)+/,'').trim()));
}
const sqlStatements=['update_haze_tips.sql','update_haze_groups.sql'].flatMap(name=>statements(fs.readFileSync(new URL('../games/supabase/'+name,import.meta.url),'utf8')));
const sqlParts=[];let chunk=[];
for(const st of sqlStatements){if(chunk.length&&chunk.join('\n').length+st.length>PART){sqlParts.push(chunk);chunk=[];}chunk.push(st);}
if(chunk.length)sqlParts.push(chunk);
const edgeLines=bundle.split('\n'),edgeParts=[];let lines=[];
for(const line of edgeLines){if(lines.length&&lines.join('\n').length+line.length>PART){edgeParts.push(lines);lines=[];}lines.push(line);}
if(lines.length)edgeParts.push(lines);
const phone=name=>new URL('../games/supabase/haze-beta/phone/'+name,import.meta.url);
const pad=n=>String(n).padStart(2,'0');
const files=[[out,bundle],[sqlOut,sql],
  ...sqlParts.map((part,i)=>[phone('sql-'+pad(i+1)+'.sql'),'-- Haze install, part '+(i+1)+' of '+sqlParts.length+'. Run the parts IN ORDER (01, 02, ...). Repeatable.\nbegin;\n'+part.join('\n')+'\ncommit;\n']),
  ...edgeParts.map((part,i)=>[phone('edge-'+pad(i+1)+'.txt'),part.join('\n')+(i<edgeParts.length-1?'\n':'')])];
const stale=fs.existsSync(phone(''))?fs.readdirSync(phone('')).filter(name=>!files.some(([file])=>file.pathname===phone(name).pathname)):[];
if(process.argv.includes('--check')){
  for(const [file,text] of files)if(!fs.existsSync(file)||fs.readFileSync(file,'utf8')!==text){console.error(file.pathname+' is stale: run node scripts/bundle-haze-edge.mjs');process.exit(1);}
  if(stale.length){console.error('Remove stale phone parts: '+stale.join(', '));process.exit(1);}
  console.log('haze beta paste files are up to date');
}else{
  fs.mkdirSync(phone(''),{recursive:true});for(const name of stale)fs.unlinkSync(phone(name));
  for(const [file,text] of files){fs.writeFileSync(file,text);console.log('wrote',file.pathname.split('/games/')[1],text.length,'bytes');}
}
