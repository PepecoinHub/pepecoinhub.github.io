"""Build games/supabase/deploy/LAUNCH_ALL.sql: every file of deploy/RUN_ORDER.md, in that order, in ONE transaction.

Each file's own top-level `begin;` / `commit;` lines are taken out, so the whole launch commits together or not at all.
Run: python3 scripts/build_launch_sql.py   (tests/launch-kit.test.mjs checks the output is up to date)
"""
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
SUPA = os.path.join(ROOT, 'games', 'supabase')
OUT = os.path.join(SUPA, 'deploy', 'LAUNCH_ALL.sql')
TX = re.compile(r'^\s*(begin|commit)\s*;\s*$', re.I)


def order():
    with open(os.path.join(SUPA, 'deploy', 'RUN_ORDER.md'), encoding='utf-8') as f:
        return re.findall(r'^\d+\. `([a-z0-9_]+\.sql)`', f.read(), re.M)


def build():
    files = order()
    parts = ['-- PepecoinHub launch: ' + str(len(files)) + ' SQL files in one transaction. GENERATED by scripts/build_launch_sql.py',
             '-- from games/supabase/deploy/RUN_ORDER.md. Do not edit here: edit the files and run the script again.',
             '-- Supabase > SQL Editor > New query > paste ALL of this > Run. Any error: nothing is applied (send the error to Claude).',
             '-- Safe to run again. Afterwards run deploy/00_check.sql: every row should say done.',
             '', 'begin;', '']
    for i, name in enumerate(files, 1):
        with open(os.path.join(SUPA, name), encoding='utf-8') as f:
            body = '\n'.join(line for line in f.read().splitlines() if not TX.match(line))
        parts += ['-- ' + '=' * 100, '-- %d/%d  %s' % (i, len(files), name), '-- ' + '=' * 100, body.rstrip(), '']
    parts += ['commit;', '']
    return '\n'.join(parts)


if __name__ == '__main__':
    text = build()
    if '--check' in sys.argv:
        with open(OUT, encoding='utf-8') as f:
            sys.exit(0 if f.read() == text else 1)
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(text)
    print('wrote', os.path.relpath(OUT, ROOT), len(text), 'bytes')
