-- Disposable local QA database only. These minimal host/auth tables are fixtures;
-- the actual Haze migration is applied after this file, without modifications.
create role anon nologin;
create role authenticated nologin;
create role service_role nologin;
create schema auth;
create schema games;
create schema realtime;
create table auth.users(id uuid primary key);
create table auth.identities(user_id uuid,provider text);
create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
create function games.discord_identity(u uuid) returns jsonb language sql stable security definer as $$select '{}'::jsonb from auth.identities where user_id=u and provider='discord'$$;
create function games.is_profane(t text) returns boolean language sql as $$select t like '%badword%'$$;
create function games.is_blocked(t text) returns boolean language sql as $$select t like '%blockedword%'$$;
create table games.profiles(user_id uuid primary key,nick text);
create table games.lobby_chat(id bigint generated by default as identity primary key,user_id uuid,nick text,body text,verified boolean,created_at timestamptz default now(),hidden_at timestamptz);
create table games.lobby_mutes(user_id uuid primary key,until timestamptz);
create table games.passport_badges(user_id uuid,badge_id text,primary key(user_id,badge_id));
create table realtime.test_rings(event text);
create function realtime.send(jsonb,text,text,boolean) returns void language sql as $$insert into realtime.test_rings values($2)$$;
grant usage on schema public,auth,games to anon,authenticated,service_role;
