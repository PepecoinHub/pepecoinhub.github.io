/**
 * Next question: your own first, then the category and general ones that were never used,
 * then whichever was used longest ago. `used` maps a question to the round it was last used in.
 */
export function pickQuestion(opts: { custom: string[]; category: Category; used: Map<string, number> }): { q: string; custom: boolean } {
  const fresh = (q: string) => !opts.used.has(q);
  const custom = opts.custom.find(fresh);
  if (custom) return { q: custom, custom: true };
  const pool = [...QUESTIONS[opts.category], ...QUESTIONS.general];
  const next = pool.find(fresh);
  if (next) return { q: next, custom: false };
  const oldest = [...pool, ...opts.custom].sort((a, b) => (opts.used.get(a) ?? 0) - (opts.used.get(b) ?? 0))[0]!;
  return { q: oldest, custom: opts.custom.includes(oldest) };
}
