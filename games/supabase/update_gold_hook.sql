-- Pepe Gold Hook: high scores in the shared arcade table. Run after the arcade setup (games.arcade_scores,
-- public.gry_arcade_submit, public.gry_arcade_top). Safe to run again. NOT YET RUN on the live project.
--
-- Pepe Gold Hook uses the EXISTING arcade ranking, like 'fud' and 'snake'. No new table, no Realtime.
--   * one call per round, and only when the player presses "Submit score";
--   * top 10: the existing public.gry_arcade_top('goldhook'), cached for a minute in the browser;
--   * the SERVER counts the points from the list of caught objects (the browser never sends a total);
--   * nickname, Discord, rate limits (network / user / global) and the best-300 trim are copied 1:1
--     from public.gry_arcade_submit, so both behave the same;
--   * public.gry_arcade_submit is NOT changed and still refuses 'goldhook', so nobody can skip the
--     check by sending a bare number;
--   * games.passport_arcade_after only rewards 'fud' and 'snake': Pepe Gold Hook gives no Passport
--     stamps (out of scope for now). Unchanged.
--
-- Changing the round layout, points or hook speeds = updating the (values ...) table below. It is
-- generated by layoutTable() in docs/games/js/gold-hook-validation.mjs; tests/gold-hook.test.mjs
-- checks that both match. Layout: layoutVersion 2.

begin;

-- 1. Allow the new game in the existing table.
alter table games.arcade_scores drop constraint arcade_scores_game_check;
alter table games.arcade_scores add constraint arcade_scores_game_check
  check (game = any (array['fud'::text, 'snake'::text, 'goldhook'::text]));

-- 2. Submit a Pepe Gold Hook score.
--    p_catches = [{"id": 5, "t": 4.075}, ...]: object id and game time of the delivery (s)
--    p_ms      = game time in ms (60000, or less when everything was collected)
create or replace function public.gry_goldhook_submit(p_nick text, p_catches jsonb, p_ms integer)
returns jsonb
language plpgsql
security definer
set search_path to ''
as $function$
declare
  u      uuid := auth.uid();
  d      jsonb := case when u is null then null else games.discord_identity(u) end;
  ip     text := games.client_ip_hash();
  v_nick text := btrim(regexp_replace(coalesce(p_nick, ''), '\s+', ' ', 'g'));
  v_score  int := 0;
  v_prev   numeric := 0;
  v_seen   int[] := '{}';
  v_id     int;
  v_t      numeric;
  v_points int;
  v_min    numeric;
  c        jsonb;
  n        int;
  place    int;
begin
  if p_catches is null or jsonb_typeof(p_catches) <> 'array' or jsonb_array_length(p_catches) = 0 then
    raise exception 'Nothing to submit';
  end if;
  if jsonb_array_length(p_catches) > 11 then
    raise exception 'That score does not add up';
  end if;
  if p_ms is null or p_ms < 5000 or p_ms > 60500 then
    raise exception 'That game was too short or too long';
  end if;

  -- Round check: every object once, rising times, and no gap shorter than the fastest possible
  -- hook cycle (×0.95 − 0.02 s). The same logic as docs/games/js/gold-hook-validation.mjs.
  for c in
    select e.value from jsonb_array_elements(p_catches) with ordinality as e(value, idx)
    order by e.idx
  loop
    if jsonb_typeof(c -> 'id') is distinct from 'number'
       or jsonb_typeof(c -> 't') is distinct from 'number'
       or (c ->> 'id') !~ '^[0-9]{1,2}$' then
      raise exception 'That score does not add up';
    end if;
    v_id := (c ->> 'id')::int;
    v_t  := (c ->> 't')::numeric;

    -- (id, points, shortest cycle in s): round 1, layoutVersion 2
    select l.points, l.min_cycle into v_points, v_min
    from (values
      (0, 50, 0.946),
      (1, 50, 0.535),
      (2, 50, 1.473),
      (3, 120, 1.905),
      (4, 120, 2.723),
      (5, 250, 4.066),
      (6, 75, 1.674),
      (7, 75, 0.849),
      (8, 10, 1.930),
      (9, 10, 3.633),
      (10, 100, 3.348)
    ) as l(id, points, min_cycle)
    where l.id = v_id;

    if v_points is null
       or v_id = any (v_seen)
       or v_t <= 0 or v_t > 60
       or v_t < v_prev
       or v_t - v_prev < v_min * 0.95 - 0.02 then
      raise exception 'That score does not add up';
    end if;

    v_seen   := v_seen || v_id;
    v_prev   := v_t;
    v_score  := v_score + v_points;
    v_points := null;
  end loop;

  -- The last delivery cannot come after the end of the stated game time.
  if v_prev * 1000 > p_ms + 500 then
    raise exception 'That score does not add up';
  end if;

  -- Rate limits: as in public.gry_arcade_submit.
  perform 1 from games.config where id = 1 for update;
  if (select count(*) from games.arcade_scores where created_at > now() - interval '1 hour') >= 300 then
    raise exception 'The high score table is busy. Try again later';
  end if;
  if ip is not null then
    select count(*) into n from games.arcade_scores where ip_hash = ip and created_at > now() - interval '10 minutes';
    if n >= 6 then raise exception 'Slow down a little, fren'; end if;
  else
    select count(*) into n from games.arcade_scores where ip_hash is null and created_at > now() - interval '10 minutes';
    if n >= 40 then raise exception 'Slow down a little, fren'; end if;
  end if;
  if u is not null then
    select count(*) into n from games.arcade_scores where user_id = u and created_at > now() - interval '10 minutes';
    if n >= 6 then raise exception 'Slow down a little, fren'; end if;
  end if;

  -- Nickname: as in public.gry_arcade_submit.
  if d is not null then
    v_nick := left(d ->> 'name', 32);
  else
    if char_length(v_nick) < 2 or char_length(v_nick) > 20 or v_nick !~ '^[A-Za-z0-9 _.\-]+$' then
      raise exception 'Nickname: 2 to 20 letters, digits, spaces, _ . -';
    end if;
    if games.is_profane(v_nick) then raise exception 'Pick a different nickname'; end if;
    if exists (select 1 from games.arcade_scores s where s.verified and lower(s.nick) = lower(v_nick)) then
      raise exception 'That name belongs to a verified player. Sign in with Discord on PEP Games, or pick another';
    end if;
  end if;

  insert into games.arcade_scores (game, nick, score, verified, user_id, duration_ms, ip_hash)
  values ('goldhook', v_nick, v_score, d is not null, case when d is not null then u end, p_ms, ip);

  -- Keep only the best 300 per game: as in public.gry_arcade_submit.
  delete from games.arcade_scores a where a.game = 'goldhook' and a.id not in (
    select id from games.arcade_scores where game = 'goldhook' order by score desc, created_at limit 300);

  select 1 + count(*) into place from (
    select max(a.score) s from games.arcade_scores a where a.game = 'goldhook'
    group by case when a.verified then a.user_id::text else 'n:' || lower(a.nick) end) t
  where t.s > v_score;

  return jsonb_build_object('nick', v_nick, 'verified', d is not null, 'place', place, 'score', v_score);
end
$function$;

revoke all on function public.gry_goldhook_submit(text, jsonb, integer) from public;
grant execute on function public.gry_goldhook_submit(text, jsonb, integer) to anon, authenticated;

commit;

